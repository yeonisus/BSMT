def fold_risk(points, normals, faces, thickness):
    """Faces where the offset is near or past the local radius of curvature.

    Cheap and local: a face whose offset copy has flipped over, or shrunk to
    almost nothing, is a face where the outer surface has folded. Reported as
    a WARNING - it catches the obvious cases, and a preview it says nothing
    about may still be locally wrong.
    """
    flipped = 0
    for face in faces:
        indices = list(face)
        base = points[indices]
        moved = base + normals[indices] * thickness
        before = _face_normal(base)
        after = _face_normal(moved)
        if before is None or after is None:
            flipped += 1
            continue
        if float(before.dot(after)) <= 0.0:
            flipped += 1
    return flipped


def _face_normal(corners):
    origin = corners[0]
    accumulated = np.zeros(3)
    for index in range(1, corners.shape[0] - 1):
        accumulated = accumulated + np.cross(corners[index] - origin,
                                             corners[index + 1] - origin)
    length = float(np.linalg.norm(accumulated))
    return None if length <= 0.0 else accumulated / length


def build_shell(points, faces, thickness, direction, tolerance):
    """The preview: base surface, offset outer surface, and the side wall.

    Returns a dict with the shell geometry and what was measured building it.
    `direction` is +1 or -1 and is applied to the vertex normals, so the
    caller decides outward once and this never guesses.

    The shell is closed on a patch whose border is a set of loops: every
    border edge gets a quad joining base to outer, so the preview reads as a
    solid from the side rather than as two floating sheets.
    """
    points, faces, _mapping = weld(points, faces, tolerance)
    if points.size == 0 or not faces:
        raise PreviewError(CODE_DEGENERATE,
                           "the interior surface has no usable faces")

    normals, usable = vertex_normals(points, faces)
    if not bool(usable.all()):
        raise PreviewError(
            CODE_DEGENERATE,
            "%d point(s) of the interior have no surface normal, so there is "
            "no direction to offset them along" % int((~usable).sum()))

    offset = normals * (float(thickness) * float(direction))
    outer = points + offset

    loops = boundary_loops(faces)
    if not loops:
        raise PreviewError(
            CODE_DEGENERATE,
            "the interior has no border, so there is nothing to build a side "
            "wall on")

    count = points.shape[0]
    shell_points = np.vstack([points, outer])
    shell_faces = []
    # Base, winding reversed so it faces away from the outer surface - the
    # preview should read as a solid from either side.
    for face in faces:
        shell_faces.append(tuple(reversed([int(index) for index in face])))
    for face in faces:
        shell_faces.append(tuple(int(index) + count for index in face))

    wall_faces = 0
    for loop in loops:
        length = len(loop)
        for index in range(length):
            a = int(loop[index])
            b = int(loop[(index + 1) % length])
            shell_faces.append((a, b, b + count, a + count))
            wall_faces += 1

    return {
        "points": shell_points,
        "faces": shell_faces,
        "base_face_count": len(faces),
        "wall_face_count": wall_faces,
        "loop_count": len(loops),
        "loop_lengths": [len(loop) for loop in loops],
        "vertex_count": int(shell_points.shape[0]),
        "folded_faces": fold_risk(points, normals * float(direction), faces,
                                  float(thickness)),
        "limits": LIMITS,
    }
